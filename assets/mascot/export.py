#!/usr/bin/env python3
"""Exports the mascot's sprites for the plugin: PNG frames here, and src/mascot.rs to embed them.

    python3 -I assets/mascot/export.py ~/code/fran/mascot

The .px files in the mascot repository are the source; this reuses its pixel.py to read them.
Each sprite's loop is reduced to its distinct frames, numbered in the order they first show, so
the loop always starts on frame 0, the one a sprite rests on. Every frame is the 16x10 art in its
dark colors (the bar and the notifications are black), centered in a 16x16 square and scaled x8
to 128x128: eave shrinks pictures by halving, so 128 -> 64 -> 32 stays pixel-sharp, and a
notification's cover crops a square from the middle, which a square loses nothing to.
"""
import importlib.util
import sys
from pathlib import Path

SPRITES = ["planning", "laptop", "question", "happy", "coffee", "sleeping"]
SIDE = 16
SCALE = 8

HERE = Path(__file__).resolve().parent
RUST = HERE.parent.parent / "src" / "mascot.rs"


def load_pixel(mascot):
    spec = importlib.util.spec_from_file_location("pixel", mascot / "pixel.py")
    pixel = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pixel)
    return pixel


def square(grid):
    width = len(grid[0])
    if width > SIDE or len(grid) > SIDE:
        sys.exit(f"art is {width}x{len(grid)}, larger than {SIDE}x{SIDE}")
    top = (SIDE - len(grid)) // 2
    left = (SIDE - width) // 2
    blank = [None] * SIDE
    rows = [list(blank) for _ in range(top)]
    rows += [[None] * left + list(row) + [None] * (SIDE - width - left) for row in grid]
    rows += [list(blank) for _ in range(SIDE - len(rows))]
    return rows


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    mascot = Path(sys.argv[1]).expanduser()
    pixel = load_pixel(mascot)
    for old in HERE.glob("*.png"):
        old.unlink()
    rust = [
        "//! The mascot's sprites. Generated by `assets/mascot/export.py` from the mascot's `.px`",
        "//! files: don't edit, export again.",
        "",
        "/// A sprite's frames, and the order they play in. It rests on frame 0, its first.",
        "pub struct Sprite {",
        "    pub frames: &'static [&'static [u8]],",
        "    pub order: &'static [u8],",
        "}",
    ]
    for name in SPRITES:
        art = pixel.parse(mascot / f"{name}.px", "dark")
        distinct, order = [], []
        for grid in art.frames:
            key = tuple(tuple(row) for row in grid)
            if key not in distinct:
                distinct.append(key)
            order.append(distinct.index(key))
        files = []
        for n, grid in enumerate(distinct):
            path = HERE / f"{name}-{n}.png"
            path.write_bytes(pixel.png(square(grid), SCALE))
            files.append(path.name)
        rust += [
            "",
            f"pub static {name.upper()}: Sprite = Sprite {{",
            "    frames: &[",
            *(f'        include_bytes!("../assets/mascot/{f}"),' for f in files),
            "    ],",
            f"    order: &[{', '.join(map(str, order))}],",
            "};",
        ]
        print(f"{name}: {len(files)} frames, order {order}")
    RUST.write_text("\n".join(rust) + "\n")
    print(RUST)


if __name__ == "__main__":
    main()
